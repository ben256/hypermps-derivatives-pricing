from model.neural_mps import NeuralMPS
from data_processing.create_dataset import generate_covariance_matrix, target_function, function_wrapper
from train.utils import find_dataset, setup_logging


def compare_cores(
    d: int,
    N: int,
    correlation: float,
    max_rank: int,
    format: str,
    decoder_type: str,
    dataset_dir: str,
    model_dir: str,
    output_dir: str,
    device: str,
):
    """
    Compares the TT cores generated by the NN model, TT-Cross, and a ground truth tensor.
    """
    logger = setup_logging(output_dir)
    device = torch.device(device)

    _, _, _, dataset_info = find_dataset(
        dataset_dir, d=d, N=N, correlation=correlation, format=format, semi_supervised=True
    )

    if format == 'TT':
        ranks = [max_rank] * (d - 1)
        n_model = N
    elif format == 'BTT':
        k = int(np.log2(N))
        n_model = 2
        ranks = [1]
        for i in range(d * k):
            if len(ranks) < (d * k) // 2:
                ranks.append(min(ranks[-1] * 2, max_rank))
            else:
                ranks.append(min(ranks[-1] * 2, max_rank))
                break
        ranks.extend(ranks[::-1][1:])
    else:
        raise ValueError(f"Unsupported format: {format}")

    model_data = torch.load(f'{model_dir}/best_model.pth', map_location=device)
    model = NeuralMPS(
        ranks=ranks,
        n=n_model,
        input_size=dataset_info['input_size'],
        decoder_type=decoder_type,
    )
    model.to(device)
    model.load_state_dict(model_data['model_state_dict'])
    model.eval()
    logger.info("Model loaded successfully.")

    rng = np.random.default_rng(4)
    A = rng.uniform(low=0.2, high=1.0)
    c = rng.uniform(low=-0.5, high=0.5, size=d)
    cov_matrix = generate_covariance_matrix(rng, d, correlation=correlation)
    cov_triu = np.triu(cov_matrix)
    cov_triu_input = cov_triu[np.triu_indices(d)]
    params = np.concatenate([[A], c, cov_triu_input])
    params_tensor = torch.from_numpy(params).to(torch.float32).to(device).unsqueeze(0)

    with torch.no_grad():
        nn_cores = model(params_tensor)
    nn_cores = [core.squeeze(0).to(torch.float32) for core in nn_cores]
    nn_tt = tn.Tensor(nn_cores)
    logger.info("Generated TT cores from the neural network.")

    if format == 'TT':
        domain = [torch.arange(N, device=device) for _ in range(d)]
    elif format == 'BTT':
        k = int(np.log2(N))
        domain = [torch.arange(2, device=device) for _ in range(d * k)]

    cross_tt = tn.cross(
        function=lambda *ix: function_wrapper(
            *ix, A=A, c=c, cov_matrix=cov_matrix, N=N, type=format, device=device
        ),
        domain=domain,
        eps=1e-7,
        ranks_tt=ranks[1:-1],
        verbose=False,
    ).to(torch.float32)
    logger.info("Generated TT cores from TT-Cross.")

    logger.info("Generating ground truth tensor. This may take a while...")
    if format == 'TT':
        grid_points = [np.linspace(-1, 1, N)] * d
        mesh = np.meshgrid(*grid_points, indexing='ij')
        full_tensor_np = target_function(np.stack([m.ravel() for m in mesh]), A, c, cov_matrix).numpy()
        full_tensor_shape = [N] * d
        full_tensor = torch.from_numpy(full_tensor_np).reshape(full_tensor_shape).to(device)

    elif format == 'BTT':
        k = int(np.log2(N))
        grid_1d = np.linspace(-1, 1, N)

        binary_indices = np.array(np.meshgrid(*([range(2)] * (d * k)), indexing='ij'))
        binary_indices = binary_indices.reshape(d * k, -1).T

        x_vectors = []
        for i in range(d):
            bits = binary_indices[:, i * k : (i + 1) * k]
            int_indices = bits.dot(1 << np.arange(k - 1, -1, -1))
            x_vectors.append(grid_1d[int_indices])

        x_vectors = np.stack(x_vectors)

        full_tensor_np = target_function(x_vectors, A, c, cov_matrix).numpy()
        full_tensor_shape = [2] * (d * k)
        full_tensor = torch.from_numpy(full_tensor_np).reshape(full_tensor_shape).to(device)

    else:
        raise ValueError(f"Unsupported format: {format}")

    ground_truth_tt = tn.Tensor(full_tensor.to(torch.float32), ranks_tt=None, verbose=True)
    logger.info("Generated ground truth TT cores via SVD.")

    error_nn = tn.relative_error(ground_truth_tt, nn_tt)
    error_cross = tn.relative_error(ground_truth_tt, cross_tt)

    logger.info(f"Relative error (NN vs Ground Truth): {error_nn.item():.6f}")
    logger.info(f"Relative error (TT-Cross vs Ground Truth): {error_cross.item():.6f}")

